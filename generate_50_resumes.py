def create_pdf(filepath, c):
    doc = SimpleDocTemplate(
        filepath,
        pagesize=letter,
        rightMargin=36,
        leftMargin=36,
        topMargin=36,
        bottomMargin=36
    )
    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        'ResumeTitle',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=18,
        textColor=colors.HexColor("#1E3A8A"),
        leading=22
    )
    subtitle_style = ParagraphStyle(
        'ResumeSubtitle',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=11,
        textColor=colors.HexColor("#2563EB"),
        leading=15
    )
    contact_style = ParagraphStyle(
        'ResumeContact',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=8.5,
        textColor=colors.HexColor("#4B5563"),
        leading=12
    )
    section_heading = ParagraphStyle(
        'SectionHeading',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=11,
        textColor=colors.HexColor("#1E3A8A"),
        spaceBefore=8,
        spaceAfter=3,
        leading=14
    )
    body_style = ParagraphStyle(
        'ResumeBody',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=9.5,
        textColor=colors.HexColor("#1F2937"),
        leading=13.5
    )
    bullet_style = ParagraphStyle(
        'ResumeBullet',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=9,
        textColor=colors.HexColor("#374151"),
        leftIndent=12,
        leading=13
    )

    story = []
    # Header
    story.append(Paragraph(c["name"], title_style))
    story.append(Paragraph(c["title"], subtitle_style))
    story.append(Spacer(1, 2))
    story.append(Paragraph(f"Email: {c['email']}  |  Phone: {c['phone']}  |  LinkedIn: linkedin.com/in/{c['name'].lower().replace(' ', '')}", contact_style))
    story.append(Spacer(1, 6))
    story.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor("#2563EB"), spaceAfter=8))

    # Summary
    story.append(Paragraph("PROFESSIONAL SUMMARY", section_heading))
    summary_text = (
        f"Goal-oriented {c['title']} with {c['exp_str']} of hands-on experience driving excellence in "
        f"{', '.join(c['skills'][:4])}. Proven ability to collaborate cross-functionally and deliver scalable business impact."
    )
    story.append(Paragraph(summary_text, body_style))
    story.append(Spacer(1, 4))

    # Skills
    story.append(Paragraph("TECHNICAL & PROFESSIONAL COMPETENCIES", section_heading))
    story.append(Paragraph(" • ".join(c['skills']), body_style))
    story.append(Spacer(1, 4))

    # Work Experience
    story.append(Paragraph("WORK EXPERIENCE", section_heading))
    role_company = f"<b>{c.get('role', c['title'])}</b> – <i>{c.get('company', 'Enterprise Systems Ltd')}</i> ({c.get('duration', '2022 - Present')})"
    story.append(Paragraph(role_company, body_style))
    for pt in c.get('points', ["Delivered core technical solutions adhering to industry standards.", "Collaborated cross-functionally across engineering & product teams."]):
        story.append(Paragraph(f"• {pt}", bullet_style))
    story.append(Spacer(1, 4))

    # Education
    story.append(Paragraph("EDUCATION & CERTIFICATIONS", section_heading))
    story.append(Paragraph(f"<b>{c['edu']}</b>", body_style))

    doc.build(story)


